//! UI strings for every supported [`Language`]. One struct per language,
//! so a missing translation is a compile error, not a runtime fallback.
//! Parameterized strings hold `{}` placeholders filled by [`fill`].

use crate::preferences::Language;

/// Replace each `{}` in `template` with the next argument, in order.
pub fn fill(template: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut parts = template.split("{}");
    let mut out = parts.next().unwrap_or_default().to_string();
    for (arg, part) in args.iter().zip(parts) {
        out.push_str(&arg.to_string());
        out.push_str(part);
    }
    out
}

impl Language {
    pub const fn strings(self) -> &'static Strings {
        match self {
            Self::English => &EN,
            Self::Spanish => &ES,
            Self::French => &FR,
            Self::German => &DE,
            Self::Italian => &IT,
        }
    }
}

