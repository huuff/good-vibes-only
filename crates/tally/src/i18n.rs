#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn fill_replaces_placeholders_in_order() {
        assert_eq!(fill("DAY {}", &[&7]), "DAY 7");
        assert_eq!(fill("{} of {} reps", &[&3, &66]), "3 of 66 reps");
        assert_eq!(fill("no placeholders", &[]), "no placeholders");
    }

    #[test]
    fn language_values_round_trip() {
        for lang in Language::ALL {
            assert_eq!(Language::from_value(lang.value()), Some(lang));
        }
        assert_eq!(Language::from_value("pt"), None);
    }
}
